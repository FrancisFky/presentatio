function adminCurrentLanguage(): string
{
    if (!isset($_SESSION['admin_language']) || !in_array($_SESSION['admin_language'], ['en', 'fr'], true)) {
        $_SESSION['admin_language'] = 'en';
    }

    return $_SESSION['admin_language'];
}

function adminSetLanguage(?string $lang): string
{
    $lang = strtolower((string) ($lang ?? 'en'));
    if (!in_array($lang, ['en', 'fr'], true)) {
        $lang = 'en';
    }

    $_SESSION['admin_language'] = $lang;
    return $lang;
}

function adminCurrentRequestUri(): string
{
    $requestUri = $_SERVER['REQUEST_URI'] ?? ($_SERVER['PHP_SELF'] ?? 'dashboard.php');
    return $requestUri ?: 'dashboard.php';
}

function adminBuildSwitchUrl(string $lang): string
{
    $target = strtolower($lang);
    if (!in_array($target, ['en', 'fr'], true)) {
        $target = 'en';
    }

    $requestUri = parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH) ?: ($_SERVER['PHP_SELF'] ?? '/admin/dashboard.php');
    $query = $_GET;
    unset($query['lang']);

    $queryString = http_build_query($query, '', '&', PHP_QUERY_RFC3986);
    $url = $requestUri;

    if ($queryString !== '') {
        $url .= '?' . $queryString;
    }

    return $url . (str_contains($url, '?') ? '&' : '?') . 'lang=' . $target;
}

function adminApplyLanguagePreference(): void
{
    if (isset($_GET['lang'])) {
        $lang = strtolower((string) $_GET['lang']);
        if (in_array($lang, ['en', 'fr'], true)) {
            adminSetLanguage($lang);

            $requestUri = parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH) ?: ($_SERVER['PHP_SELF'] ?? '/admin/dashboard.php');
            $query = $_GET;
            unset($query['lang']);

            $redirectTarget = $requestUri;
            $queryString = http_build_query($query, '', '&', PHP_QUERY_RFC3986);
            if ($queryString !== '') {
                $redirectTarget .= '?' . $queryString;
            }

            header('Location: ' . $redirectTarget, true, 303);
            exit;
        }
    }

    adminCurrentLanguage();
}

function __admin(string $key, array $params = []): string
{
    global $adminTranslations;

    $language = adminCurrentLanguage();
    $selected = $adminTranslations[$language][$key] ?? $adminTranslations['en'][$key] ?? $key;

    foreach ($params as $name => $value) {
        $selected = str_replace('{' . $name . '}', (string) $value, $selected);
    }

    return $selected;
}
